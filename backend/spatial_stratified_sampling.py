import pandas as pd

def two_tier_stratified_sampling(input_csv, sub_cap=80, main_cap=250, seed=42):
    print("--- INITIATING SPATIAL CAPPING ---")
    
    # 1. Load the mapped dataset
    df = pd.read_csv(input_csv)
    original_len = len(df)
    
    # 2. Drop unmapped 'Unknown' locations
    df = df[df['Main_District'] != 'Unknown']
    print(f"Dropped {original_len - len(df)} unmapped rows.")
    
    # 3. Tier 1: Micro Cap (Sub-Location Level)
    df_micro = (df.groupby('Official_Sub_Location', group_keys=False)
                  .apply(lambda x: x.sample(min(len(x), sub_cap), random_state=seed)))
    
    # 4. Tier 2: Macro Cap (Main District Level)
    df_balanced = (df_micro.groupby('Main_District', group_keys=False)
                           .apply(lambda x: x.sample(min(len(x), main_cap), random_state=seed)))
                           
    print(f"Balanced Dataset Size: {len(df_balanced)} rows.")
    
    # 5. Save the prepped dataset
    output_name = 'lagos_rent_spatially_capped.csv'
    df_balanced.to_csv(output_name, index=False)
    print(f"Success. Saved perfectly balanced training data to '{output_name}'.")

if __name__ == "__main__":
    # Point this to the CSV generated by the cleaning script
    two_tier_stratified_sampling('lagos_rent_strictly_mapped.csv', sub_cap=80, main_cap=250)